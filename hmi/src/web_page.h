"const x=new XMLHttpRequest();x.open('POST','/update/'+kind);"
"x.upload.onprogress=e=>say('Uploading '+Math.round(100*e.loaded/e.total)+'%');"
"x.onload=()=>{say(x.responseText);poll()};x.onerror=()=>say(kind=='hmi'?'Connection closed. If the upload had finished, the controller is restarting.':'Upload failed.');"
"x.send(f)}"
"async function push(i){const r=await fetch('/node/push?i='+i,{method:'POST'});say(await r.text());poll()}"
"poll();setInterval(poll,2000);"
"</script></html>";

